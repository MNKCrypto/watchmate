"""Evaluate WatchMate's real outputs (examples/) against what each subscriber asked for.

No model calls: it checks the saved reels, timelines and decision log.

    python -m evals.evaluate            # prints the results and writes evals/RESULTS.md
    python -m evals.evaluate --check    # exit code 1 if any check fails (used in CI)

Checks per reel
  budget       total length <= the subscriber's requested length
  in range     clips inside the video, in order, no overlaps
  self-check   every clip was re-watched by Muse Spark and passed (or was retitled/replaced)
  hard rules   no clip falls in a moment the subscriber asked to skip (e.g. politics/budget, interviews)
  live         for a fan who prefers live footage: share of reel time from live/mixed moments
Checks per broadcast
  matching     who was served / skipped matches what each subscriber asked for, and every skip has a reason
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def load(rel: str):
    return json.loads((ROOT / rel).read_text())


def moments_hit(clip: dict, moments: list[dict]) -> list[dict]:
    return [m for m in moments if not (clip["end_seg"] < m["start_seg"] or clip["start_seg"] > m["end_seg"])]


def eval_reel(case: dict) -> tuple[str, list[tuple[str, bool, str]]]:
    reel, timeline = load(case["reel"]), load(case["timeline"])
    moments, clips = timeline["moments"], reel["clips"]
    last_seg = moments[-1]["end_seg"]
    checks = []

    budget = reel["profile"]["max_seconds"]
    checks.append(("budget", reel["total_seconds"] <= budget, f"{reel['total_seconds']:.0f}s of {budget}s"))

    ordered = all(0 <= c["start_seg"] <= c["end_seg"] <= last_seg for c in clips) and all(
        a["end_seg"] < b["start_seg"] for a, b in zip(clips, clips[1:]))
    checks.append(("in range", ordered, f"{len(clips)} clips, no overlaps"))

    verdicts = [v.get("verdict") for v in reel.get("verification", [])]
    checked = all(c.get("verified") for c in clips) and len(verdicts) >= len(clips)
    summary = ", ".join(f"{verdicts.count(v)} {v}" for v in ("pass", "retitle", "fail") if verdicts.count(v))
    checks.append(("self-check", checked, summary or "none"))

    bad = [(c.get("title", "?"), m["type"], m["footage"]) for c in clips for m in moments_hit(c, moments)
           if m["type"] in case["forbidden_moment_types"] or m["footage"] in case["forbidden_footage"]]
    checks.append(("hard rules", not bad, f"'{case['rule']}': " + ("respected" if not bad else f"broken by {bad}")))

    if case.get("prefers_live"):
        seg_total = live = 0
        for c in clips:
            for s in range(c["start_seg"], c["end_seg"] + 1):
                seg_total += 1
                m = next(m for m in moments if m["start_seg"] <= s <= m["end_seg"])
                live += m["footage"] in ("live", "mixed")
        share = live / seg_total if seg_total else 0
        checks.append(("live", share >= 0.8, f"{share:.0%} of reel time from live/mixed footage"))

    who = reel["profile"].get("display_name", "?")
    return f"{who} · {reel['video_id']}", checks


def eval_matches(cases: list[dict]) -> list[tuple[str, bool, str]]:
    events = [json.loads(l) for l in (ROOT / "examples/decision_log.jsonl").read_text().splitlines() if l.strip()]
    current, decisions = None, {}
    for e in events:  # match events follow the broadcast they belong to
        if e["kind"] == "broadcast":
            current = e["video_id"]
        elif e["kind"] == "match":
            decisions[(current, e["user"])] = e
    out = []
    for c in cases:
        d = decisions.get((c["video"], c["user"]))
        ok = d is not None and d["relevant"] == c["expected"] and bool(d.get("reason"))
        got = "missing" if d is None else ("served" if d["relevant"] else "skipped") + f" — “{d.get('reason', '')}”"
        out.append((f"{c['user']} · {c['video']}", ok, got))
    return out


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true", help="exit 1 if any check fails")
    args = p.parse_args()
    spec = json.loads((Path(__file__).with_name("cases.json")).read_text())

    lines = ["# Evaluation results", "",
             "Generated by `python -m evals.evaluate` from the real outputs in [`examples/`](../examples/README.md) "
             "(no model calls). Rules come from each subscriber's own words — see [`cases.json`](cases.json).", "",
             "## Reels", "", "| Reel | Check | Result | Detail |", "|---|---|---|---|"]
    failed = total = 0
    for case in spec["reels"]:
        name, checks = eval_reel(case)
        for label, ok, detail in checks:
            total += 1
            failed += not ok
            lines.append(f"| {name} | {label} | {'✅' if ok else '❌'} | {detail} |")
    lines += ["", "## Who gets served", "", "| Subscriber · video | Result | Decision |", "|---|---|---|"]
    for label, ok, detail in eval_matches(spec["matches"]):
        total += 1
        failed += not ok
        lines.append(f"| {label} | {'✅' if ok else '❌'} | {detail} |")
    lines += ["", f"**{total - failed}/{total} checks passed.**", "",
              "_Limits: moment types (e.g. `politics/budget`, `interview`) come from WatchMate's own timeline, "
              "so this checks that the reels obey each subscriber's rules given that timeline — it is not an "
              "independent human labelling of the broadcast._", ""]

    report = "\n".join(lines)
    (Path(__file__).with_name("RESULTS.md")).write_text(report)
    print(report)
    if args.check and failed:
        sys.exit(1)


if __name__ == "__main__":
    main()
